CREATE TABLE electrical_testing_tally (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id UUID NOT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    record_date DATE NOT NULL,
    category_id BIGINT REFERENCES electrical_testing_category(id),
    tally_type VARCHAR(32) NOT NULL CHECK (tally_type IN ('UNTESTED_BROKEN_FAILED', 'TESTED_AND_PRICED', 'STOCK_CULL', 'DIVERTED_TO_OLS', 'DIVERTED_TO_COLL')),
    count INTEGER NOT NULL CHECK (count > 0),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES app_user(id),
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_by BIGINT REFERENCES app_user(id),
    deleted_at TIMESTAMPTZ,
    CHECK ((deleted_by IS NULL) = (deleted_at IS NULL)),
    CHECK ((tally_type IN ('UNTESTED_BROKEN_FAILED', 'TESTED_AND_PRICED', 'STOCK_CULL') AND category_id IS NOT NULL)
        OR (tally_type IN ('DIVERTED_TO_OLS', 'DIVERTED_TO_COLL') AND category_id IS NULL))
);
CREATE INDEX electrical_testing_tally_date ON electrical_testing_tally (record_date DESC, id DESC) WHERE deleted_at IS NULL;
CREATE TABLE electrical_testing_sales_reference (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id UUID NOT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    reporting_month DATE NOT NULL CHECK (EXTRACT(DAY FROM reporting_month) = 1),
    category_id BIGINT NOT NULL REFERENCES electrical_testing_category(id),
    sold_last_month_count INTEGER NOT NULL CHECK (sold_last_month_count >= 0),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES app_user(id),
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_by BIGINT REFERENCES app_user(id),
    deleted_at TIMESTAMPTZ,
    CHECK ((deleted_by IS NULL) = (deleted_at IS NULL))
);
CREATE UNIQUE INDEX electrical_testing_sales_month_category ON electrical_testing_sales_reference (reporting_month, category_id) WHERE deleted_at IS NULL;
