CREATE TABLE collectable_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id UUID NOT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    record_date DATE NOT NULL,
    gross_weight NUMERIC(10,2) NOT NULL CHECK (gross_weight > 2.00),
    tare_weight NUMERIC(10,2) NOT NULL CHECK (tare_weight = 2.00),
    net_weight NUMERIC(10,2) NOT NULL CHECK (net_weight > 0),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES app_user(id),
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_by BIGINT REFERENCES app_user(id),
    deleted_at TIMESTAMPTZ,
    CHECK (net_weight = gross_weight - tare_weight),
    CHECK ((deleted_by IS NULL) = (deleted_at IS NULL))
);

CREATE INDEX collectable_record_date ON collectable_record (record_date DESC, id DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE collectable_material (
    collectable_record_id BIGINT NOT NULL REFERENCES collectable_record(id),
    material_category_id BIGINT NOT NULL REFERENCES material_category(id),
    percentage NUMERIC(5,2) NOT NULL CHECK (percentage > 0 AND percentage <= 100),
    material_weight NUMERIC(10,2) NOT NULL CHECK (material_weight >= 0),
    PRIMARY KEY (collectable_record_id, material_category_id)
);

-- Collectables has its own applicability mapping from the approved Collectable Tub Datasheet.
INSERT INTO material_category_applicability (context, material_category_id)
SELECT 'COLLECTABLES', id FROM material_category WHERE name IN (
    'Iron and Steel', 'Aluminium', 'Other Non-Ferrous Metals', 'Mixed Metals',
    'Textiles', 'Mattresses', 'Timber', 'Bricks, Blocks and Pavers',
    'Building and Demolition Material', 'Paper, Cardboard and Books',
    'Plastics', 'Glass', 'Mixed Materials'
);
