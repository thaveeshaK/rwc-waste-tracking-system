CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('STAFF', 'ADMIN'))
);

CREATE UNIQUE INDEX app_user_single_staff ON app_user (role) WHERE role = 'STAFF';

CREATE TABLE container_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    tare_weight NUMERIC(10,2) NOT NULL CHECK (tare_weight >= 0),
    active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE material_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE crate_pallet_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id UUID NOT NULL UNIQUE,
    record_date DATE NOT NULL,
    container_type_id BIGINT NOT NULL REFERENCES container_type(id),
    gross_weight NUMERIC(10,2) NOT NULL CHECK (gross_weight >= 0),
    tare_weight NUMERIC(10,2) NOT NULL CHECK (tare_weight >= 0),
    net_weight NUMERIC(10,2) NOT NULL CHECK (net_weight >= 0),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES app_user(id),
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_by BIGINT REFERENCES app_user(id),
    deleted_at TIMESTAMPTZ,
    CHECK (net_weight = gross_weight - tare_weight),
    CHECK ((deleted_by IS NULL) = (deleted_at IS NULL))
);

CREATE INDEX crate_pallet_record_date ON crate_pallet_record (record_date DESC, id DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE crate_pallet_material (
    crate_pallet_record_id BIGINT NOT NULL REFERENCES crate_pallet_record(id),
    material_category_id BIGINT NOT NULL REFERENCES material_category(id),
    percentage NUMERIC(5,2) NOT NULL CHECK (percentage > 0 AND percentage <= 100),
    material_weight NUMERIC(10,2) NOT NULL CHECK (material_weight >= 0),
    PRIMARY KEY (crate_pallet_record_id, material_category_id)
);
