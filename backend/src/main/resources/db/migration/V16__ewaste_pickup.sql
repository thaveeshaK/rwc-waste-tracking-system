-- Dedicated collection/intake aggregate. Electrical Crate/Pallet remains internal processing.
CREATE TABLE ewaste_pickup_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 submission_id UUID NOT NULL UNIQUE,
 version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
 record_date DATE NOT NULL,
 organisation VARCHAR(255) NOT NULL CHECK (length(btrim(organisation)) > 0),
 entered_weight NUMERIC(10,2) NOT NULL CHECK (entered_weight > 0),
 total_tare_weight NUMERIC(10,2) NOT NULL CHECK (total_tare_weight >= 0),
 net_weight NUMERIC(10,2) NOT NULL CHECK (net_weight > 0),
 created_by BIGINT NOT NULL REFERENCES app_user(id), created_at TIMESTAMPTZ NOT NULL,
 updated_by BIGINT NOT NULL REFERENCES app_user(id), updated_at TIMESTAMPTZ NOT NULL,
 deleted_by BIGINT REFERENCES app_user(id), deleted_at TIMESTAMPTZ,
 CHECK (net_weight = entered_weight - total_tare_weight),
 CHECK ((deleted_by IS NULL) = (deleted_at IS NULL))
);
CREATE TABLE ewaste_pickup_container (
 ewaste_pickup_record_id BIGINT NOT NULL REFERENCES ewaste_pickup_record(id),
 container_type_id BIGINT NOT NULL REFERENCES container_type(id),
 container_name VARCHAR(100) NOT NULL,
 tare_per_unit NUMERIC(10,2) NOT NULL CHECK (tare_per_unit >= 0),
 quantity INTEGER NOT NULL CHECK (quantity > 0),
 tare_subtotal NUMERIC(10,2) NOT NULL CHECK (tare_subtotal >= 0),
 PRIMARY KEY (ewaste_pickup_record_id, container_type_id),
 CHECK (tare_subtotal = quantity * tare_per_unit)
);
CREATE INDEX ewaste_pickup_record_date ON ewaste_pickup_record(record_date DESC,id DESC) WHERE deleted_at IS NULL;
