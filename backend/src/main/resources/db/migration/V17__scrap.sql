CREATE TABLE scrap_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id UUID NOT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    reporting_month DATE NOT NULL CHECK (EXTRACT(DAY FROM reporting_month) = 1),
    iron_and_steel_weight NUMERIC(10,2) NOT NULL CHECK (iron_and_steel_weight >= 0),
    aluminium_weight NUMERIC(10,2) NOT NULL CHECK (aluminium_weight >= 0),
    other_non_ferrous_weight NUMERIC(10,2) NOT NULL CHECK (other_non_ferrous_weight >= 0),
    mixed_metals_weight NUMERIC(10,2) NOT NULL CHECK (mixed_metals_weight >= 0),
    ewaste_weight NUMERIC(10,2) NOT NULL CHECK (ewaste_weight >= 0),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES app_user(id),
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_by BIGINT REFERENCES app_user(id),
    deleted_at TIMESTAMPTZ,
    CHECK (iron_and_steel_weight + aluminium_weight + other_non_ferrous_weight + mixed_metals_weight + ewaste_weight > 0),
    CHECK ((deleted_by IS NULL) = (deleted_at IS NULL))
);
CREATE INDEX scrap_record_month ON scrap_record(reporting_month DESC, id DESC) WHERE deleted_at IS NULL;
-- Additive entries: reporting_month is deliberately not unique; summaries are derived.
