CREATE TABLE whitegoods_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id UUID NOT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    record_date DATE NOT NULL,
    whitegoods_count INTEGER NOT NULL CHECK (whitegoods_count >= 0),
    kg_per_item NUMERIC(5,2) NOT NULL CHECK (kg_per_item = 48.00),
    estimated_weight NUMERIC(12,2) NOT NULL CHECK (estimated_weight >= 0),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES app_user(id),
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_by BIGINT REFERENCES app_user(id),
    deleted_at TIMESTAMPTZ,
    CHECK (estimated_weight = whitegoods_count * kg_per_item),
    CHECK ((deleted_by IS NULL) = (deleted_at IS NULL))
);
CREATE INDEX whitegoods_record_date ON whitegoods_record (record_date DESC, id DESC) WHERE deleted_at IS NULL;
-- Dates are deliberately not unique. Monthly totals are queried from active daily entries.
