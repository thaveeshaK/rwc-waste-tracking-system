CREATE TABLE salvage_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id UUID NOT NULL UNIQUE,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    record_date DATE NOT NULL,
    crew VARCHAR(255) NOT NULL CHECK (length(trim(crew)) > 0),
    time_up TIME NOT NULL,
    kg_up NUMERIC(10,2) NOT NULL CHECK (kg_up >= 0),
    time_down TIME NOT NULL,
    kg_down NUMERIC(10,2) NOT NULL CHECK (kg_down >= 0),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES app_user(id),
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_by BIGINT REFERENCES app_user(id),
    deleted_at TIMESTAMPTZ,
    CHECK ((deleted_by IS NULL) = (deleted_at IS NULL))
);

CREATE INDEX salvage_record_date ON salvage_record (record_date DESC, id DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE salvage_material (
    salvage_record_id BIGINT NOT NULL REFERENCES salvage_record(id),
    direction VARCHAR(4) NOT NULL CHECK (direction IN ('UP', 'DOWN')),
    material_category_id BIGINT NOT NULL REFERENCES material_category(id),
    percentage NUMERIC(5,2) NOT NULL CHECK (percentage > 0 AND percentage <= 100),
    material_weight NUMERIC(10,2) NOT NULL CHECK (material_weight >= 0),
    PRIMARY KEY (salvage_record_id, direction, material_category_id)
);
